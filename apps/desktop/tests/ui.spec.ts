test.beforeAll(async () => {
  rmSync(USER_DATA, { recursive: true, force: true })
  rmSync(OUTPUT_DIR, { recursive: true, force: true })
  mkdirSync(OUTPUT_DIR, { recursive: true })
  execFileSync(VENV_PYTHON, [join(REPO, 'tests/e2e/prepare_ui.py'), join(USER_DATA, 'engine'), OUTPUT_DIR], { stdio: 'pipe' })
  // A tiny placeholder GGUF lets the UI test exercise the local-provider flow
  // without downloading 610 MiB. It is never loaded; real inference is tested
  // against the actual Qwen file outside Playwright.
  execFileSync(VENV_PYTHON, ['-c', `
import sqlite3
from pathlib import Path
from shorts_engine.models.manager import _aggregate_sha
root = Path(${JSON.stringify(join(USER_DATA, 'engine'))})
model_dir = root / 'models' / 'llm' / 'qwen3-0.6b'
model_dir.mkdir(parents=True, exist_ok=True)
(model_dir / 'Qwen3-0.6B-Q8_0.gguf').write_bytes(b'fake GGUF for UI test')
digest, total = _aggregate_sha(model_dir)
con = sqlite3.connect(root / 'clipwright.sqlite3')
con.execute("INSERT OR REPLACE INTO model_registry(id,kind,name,version,path,sha256,bytes,installed_at,meta_json) VALUES(?,?,?,?,?,?,?,?,?)", ('ui-llm', 'llm', 'qwen3-0.6b', 'ui-test', str(model_dir), digest, total, '2026-01-01T00:00:00Z', '{}'))
con.commit()
con.close()
`], { stdio: 'pipe' })
  stub = await startStub()
  const env: Record<string, string> = {}
  for (const [key, value] of Object.entries(process.env)) {
    if (key !== 'ELECTRON_RUN_AS_NODE' && value !== undefined) env[key] = value
  }
  if (process.env.CLIPWRIGHT_E2E_EMPTY_PATH) {
    mkdirSync('/tmp/emptybin', { recursive: true })
    env.PATH = '/tmp/emptybin'
  }
  Object.assign(env, {
    CLIPWRIGHT_USER_DATA: USER_DATA,
    CLIPWRIGHT_E2E: '1',
    CLIPWRIGHT_E2E_OPEN_FILE: FIXTURE,
    CLIPWRIGHT_E2E_OUTPUT_DIR: OUTPUT_DIR
  })
  const executablePath = process.env.CLIPWRIGHT_E2E_EXECUTABLE
  app = executablePath
    ? await electron.launch({ executablePath, args: ['--no-sandbox'], cwd: APP_DIR, env })
    : await electron.launch({ args: ['.', '--no-sandbox'], cwd: APP_DIR, env })
  page = await app.firstWindow()
  page.on('pageerror', (error) => console.log('PAGEERROR', error.message))
  await page.waitForLoadState('domcontentloaded')
})

test.afterAll(async () => {
  await app?.close().catch(() => undefined)
  await new Promise<void>((resolveClose) => stub?.server.close(() => resolveClose()))
})

