type Stub = { server: Server; baseUrl: string; requests: number }

function segmentIds(text: string): string[] {
  return [...text.matchAll(/\[(s\d{4,6})\|\d{2}:\d{2}:\d{2}\]/g)].map((m) => m[1])
}

function rating(score: number, evidence: string) {
  return { score, evidence }
}

async function startStub(): Promise<Stub> {
  const state: Stub = { server: createServer(), baseUrl: '', requests: 0 }
  state.server.on('request', (req, res) => {
    let raw = ''
    req.on('data', (chunk) => (raw += chunk))
    req.on('end', () => {
      if (req.method === 'GET' && req.url?.endsWith('/models')) {
        res.writeHead(200, { 'Content-Type': 'application/json', 'x-ratelimit-limit-requests': '1000' })
        res.end(JSON.stringify({ data: [{ id: 'stub-model', owned_by: 'test' }] }))
        return
      }
      state.requests += 1
      let body: any = {}
      try { body = JSON.parse(raw) } catch { /* ignore */ }
      const messages = body.messages || []
      const system = messages.find((m: any) => m.role === 'system')?.content || ''
      const user = messages.find((m: any) => m.role === 'user')?.content || ''
      let content = '{}'
      if (String(body.response_format?.json_schema?.name || '').includes('Capability') || system.includes('Reply with JSON only')) {
        content = JSON.stringify({ ok: true })
      } else if (user.includes('Candidate summaries') || (system.toLowerCase().includes('rank') && user.includes('ranking'))) {
        const candidates = [...user.matchAll(/\[(\d+)\] (s\d{4,6})-(s\d{4,6})/g)]
        content = JSON.stringify({
          ranking: candidates.map((m, i) => ({ start_seg: m[2], end_seg: m[3], rank: i + 1, best_overall: i === 0 }))
        })
      } else if (system.toLowerCase().includes('publishing metadata')) {
        content = JSON.stringify({
          title: 'A clear test title',
          description: 'A short description generated by the local test stub.',
          hashtags: ['#test', '#clips'],
          hook_suggestions: ['Start with the question.'],
          thumbnail_text: ['SMALL MOMENTS'],
          thumbnail_time_s: 1.5
        })
      } else {
        const ids = segmentIds(user)
        if (ids.length) {
          content = JSON.stringify({
            candidates: [
              {
                category: 'educational',
                start_seg: ids[0],
                end_seg: ids[ids.length - 1],
                title: 'The whole idea in one pass',
                excerpt: 'A test excerpt taken from the transcript.',
                rationale: 'It states the idea and lands it with a clear closing line.',
                ratings: {
                  hook_strength: rating(4, 'Opens by naming the subject directly.'),
                  context_completeness: rating(5, 'The full explanation is inside the clip.'),
                  ending_quality: rating(4, 'Ends after the closing line.'),
                  standalone_clarity: rating(5, 'No earlier context is required.')
                },
                weaknesses: ['Synthetic test audio.']
              }
            ]
          })
        }
      }
      res.writeHead(200, {
        'Content-Type': 'application/json',
        'x-ratelimit-limit-requests': '1000',
        'x-ratelimit-remaining-requests': '999',
        'x-ratelimit-limit-tokens': '8000',
        'x-ratelimit-remaining-tokens': '7900',
        'x-ratelimit-reset-tokens': '60s'
      })
      res.end(JSON.stringify({
        choices: [{ message: { content } }],
        usage: { prompt_tokens: 400, completion_tokens: 200, total_tokens: 600 },
        model: body.model || 'stub-model'
      }))
    })
  })
  await new Promise<void>((resolveListen) => state.server.listen(0, '127.0.0.1', resolveListen))
  const address = state.server.address()
  if (!address || typeof address === 'string') throw new Error('stub failed to bind')
  state.baseUrl = `http://127.0.0.1:${address.port}/v1`
  return state
}

let app: ElectronApplication
